import os, urllib.request
from google.colab import files
FASTA_PATH = "/content/_GCF_029882485.1_ASM2988248v1_genomic.fna"

print("Using file:", FASTA_PATH, f"({os.path.getsize(FASTA_PATH):,} bytes)")

"""## 2. Count codons (sliding window, step = 1)"""

import itertools
from collections import Counter

ALL_CODONS = ["".join(p) for p in itertools.product("UCAG", repeat=3)]

def read_fasta(path):
    """Return a list of (header, sequence) tuples."""
    records, header, chunks = [], None, []
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith(";"):
                continue
            if line.startswith(">"):
                if header is not None or chunks:
                    records.append((header or "unnamed", "".join(chunks)))
                header, chunks = line[1:].strip(), []
            else:
                chunks.append(line)
    if header is not None or chunks:
        records.append((header or "unnamed", "".join(chunks)))
    if not any(seq for _, seq in records):
        raise ValueError("No sequence data found - is this a FASTA file?")
    return records

def count_codons(sequence):
    # Window of 3, moving 1 nucleotide at a time. T is converted to U.
    seq = sequence.upper().replace("T", "U")
    raw = Counter(seq[i:i + 3] for i in range(len(seq) - 2))
    counts = {c: raw.get(c, 0) for c in ALL_CODONS}
    skipped = sum(raw.values()) - sum(counts.values())
    return counts, skipped

records = read_fasta(FASTA_PATH)
counts, skipped = dict.fromkeys(ALL_CODONS, 0), 0
for _, seq in records:
    c, s = count_codons(seq)
    skipped += s
    for codon, n in c.items():
        counts[codon] += n

total = sum(counts.values())
top10 = sorted(ALL_CODONS, key=lambda c: (-counts[c], c))[:10]
genome_name = records[0][0].split(",")[0][:70]

print(genome_name)
print(f"{sum(len(s) for _, s in records):,} nt | {total:,} codons counted | {skipped:,} windows skipped")

"""## 3. Graphs"""

import matplotlib.pyplot as plt

TOP_COLOR, OTHER_COLOR = "#e67e22", "#b0b7c3"
rank = {c: i + 1 for i, c in enumerate(top10)}
pct = {c: 100 * counts[c] / total for c in ALL_CODONS}

# All 64 codons, top 10 highlighted
fig, ax = plt.subplots(figsize=(20, 6))
bars = ax.bar(ALL_CODONS, [counts[c] for c in ALL_CODONS],
              color=[TOP_COLOR if c in rank else OTHER_COLOR for c in ALL_CODONS])
for bar, c in zip(bars, ALL_CODONS):
    if c in rank:
        ax.annotate(f"#{rank[c]}", (bar.get_x() + bar.get_width() / 2, bar.get_height()),
                    ha="center", va="bottom", fontsize=9, fontweight="bold", color=TOP_COLOR)
for x in (15.5, 31.5, 47.5):                    # separate U / C / A / G first-base groups
    ax.axvline(x, color="grey", lw=0.6, ls="--")
ax.set_title(f"Frequency of all 64 codons — {genome_name}", fontsize=14)
ax.set_ylabel("Count")
ax.set_xlim(-0.6, 63.6)
ax.tick_params(axis="x", rotation=90, labelsize=9)
for label in ax.get_xticklabels():
    if label.get_text() in rank:
        label.set_color(TOP_COLOR); label.set_fontweight("bold")
ax.legend(handles=[plt.Rectangle((0, 0), 1, 1, color=TOP_COLOR),
                   plt.Rectangle((0, 0), 1, 1, color=OTHER_COLOR)],
          labels=["Top 10", "Other codons"], loc="lower right",
          bbox_to_anchor=(1, 1.0), ncol=2, frameon=False)
ax.set_ylim(0, max(counts.values()) * 1.08)
ax.spines[["top", "right"]].set_visible(False)
plt.tight_layout()
plt.show()

# Top 10 in descending order
fig, ax = plt.subplots(figsize=(10, 5.5))
values = [counts[c] for c in top10]
ax.barh(range(10), values, color=TOP_COLOR)
ax.set_yticks(range(10), [f"#{i + 1}  {c}" for i, c in enumerate(top10)], fontfamily="monospace")
ax.invert_yaxis()
for i, c in enumerate(top10):
    ax.text(values[i], i, f"  {counts[c]:,}  ({pct[c]:.2f}%)", va="center", fontsize=10)
ax.set_xlim(0, max(values) * 1.25)
ax.set_xlabel("Count")
ax.set_title("Top 10 most frequent codons", fontsize=14)
ax.spines[["top", "right"]].set_visible(False)
plt.tight_layout()
