"""# Putting together the genome

### 1. Loading the samples
"""

with open('samples.txt') as f:
    samples = f.read().split('\n')

MAX_LEN = max(len(s) for s in samples)

print(f"Loaded {len(samples):,} samples")

"""### 2. Matching up the samples and building the seed"""

from collections import defaultdict

# build lookup dict based on first 10 letters
def build_index(seqs):
    index = defaultdict(list)
    for i, s in enumerate(seqs):
        index[s[:MIN_OVERLAP]].append(i)
    return index

def extend_right(seed, seqs, index, used):
    """Keep gluing samples onto the seed's right end until none fits."""
    while True:
        best, best_overlap = None, 0
        n = len(seed)

        for pos in range(max(0, n - MAX_LEN), n - MIN_OVERLAP + 1):
            for i in index.get(seed[pos:pos + MIN_OVERLAP], []):
                if used[i]:
                    continue
                s = seqs[i]
                overlap = n - pos
                if len(s) <= overlap:
                    # sample lies completely inside the seed: nothing new, disregard
                    if seed[pos:pos + len(s)] == s:
                        used[i] = True
                    continue
                # the sample's start must match the seed's end exactly;
                # prefer the longest overlap, it's the least likely to be a coincidence
                if s[:overlap] == seed[pos:] and overlap > best_overlap:
                    best, best_overlap = i, overlap
        if best is None:
            return seed # nothing fits: this seed is finished
        used[best] = True
        seed += seqs[best][best_overlap:] # add only the new letters

reversed_samples = [s[::-1] for s in samples]
index_fwd = build_index(samples)
index_rev = build_index(reversed_samples)
used = [False] * len(samples)

strings = []
for i in sorted(range(len(samples)), key=lambda i: -len(samples[i])):
    if used[i]:
        continue
    used[i] = True
    seed = samples[i]
    seed = extend_right(seed, samples, index_fwd, used)                       # grow right
    seed = extend_right(seed[::-1], reversed_samples, index_rev, used)[::-1]  # grow left
    strings.append(seed)

strings.sort(key=len, reverse=True)
with open('strings.txt', 'w') as f:
    f.write('\n'.join(strings))

print(f"Strings built: {len(strings):,}")
print(f"Longest string: {len(strings[0]):,} letters")
print(f"Total length: {sum(map(len, strings)):,} letters")

